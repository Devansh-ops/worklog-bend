import assert from 'node:assert/strict';
import { encodeEvent, mergeEvents, replayEvents, eligibleContext, requestContext, validateCommand, validateProposal, EventConflictError } from '../js/domain.js';
const event = (id, type, payload = {}, ts = '2026-11-07T09:00:00.000Z') => ({ id, type, ts, ...payload });
const create = event('a', 'task.create', { taskId: 'T-aaa111', title: 'Synthetic public', status: 'todo', extension: { preserved: ['x', 2] } });
const done = event('b', 'task.status', { taskId: 'T-aaa111', to: 'done' }, '2026-11-07T11:00:00.000Z');
const late = event('c', 'task.status', { taskId: 'T-aaa111', to: 'blocked' }, '2026-11-07T10:00:00.000Z');
assert.deepEqual(mergeEvents([done, create], [create, late]).map(value => value.id), ['a', 'c', 'b']);
assert.deepEqual(mergeEvents([create])[0].extension, create.extension);
assert.throws(() => mergeEvents([create], [{ ...create, title: 'Collision' }]), EventConflictError);
assert.throws(() => mergeEvents([{ ...create, ts: '2026-02-30T00:00:00.000Z' }]), /calendar/);
const original = structuredClone(create);
const replayed = replayEvents([done, create, late]);
assert.equal(replayed.tasks.get('T-aaa111').status, 'done');
assert.equal(replayed.tasks.get('T-aaa111').done, done.ts);
assert.deepEqual(create, original);
const reopened = event('d', 'task.edit', { taskId: 'T-aaa111', fields: { status: 'todo' } }, '2026-11-07T12:00:00.000Z');
assert.equal(replayEvents([create, done, reopened]).tasks.get('T-aaa111').done, null);
const createdDone = { ...create, status: 'done' };
assert.equal(replayEvents([createdDone]).tasks.get('T-aaa111').done, create.ts);
const note1 = event('n1', 'task.note', { taskId: 'T-aaa111', text: 'NOTE_CANARY' });
const note2 = { ...note1, id: 'n2' };
assert.equal(replayEvents([create, note1, note2, note1]).tasks.get('T-aaa111').notes.length, 2);
assert.equal(eligibleContext([create, note1], false)[0].notes.length, 0);
assert.ok(!JSON.stringify(requestContext([create, note1], false, { startDay: '2026-11-01', endDay: '2026-11-08' })).includes('NOTE_CANARY'));
const privateTask = event('p', 'task.create', { taskId: 'T-secret', title: 'PRIVATE_CANARY', private: true });
const privateNote = event('q', 'task.note', { taskId: 'T-secret', text: 'PRIVATE_NOTE_CANARY' }, '2026-11-07T10:00:00.000Z');
const deleted = event('r', 'task.delete', { taskId: 'T-secret' }, '2026-11-07T11:00:00.000Z');
const summary = event('s', 'summary.set', { date: '2026-11-07', kind: 'evening', summary: { headline: 'DERIVED_CANARY', bullets: [], risks: [], next: [] } });
const report = event('t', 'standup.set', { date: '2026-11-07', kind: 'evening', text: 'REPORT_CANARY', style: 'markdown' });
const history = [create, privateTask, privateNote, deleted, summary, report];
const context = requestContext(history, true, { startDay: '2026-11-01', endDay: '2026-11-08' });
for (const secret of ['PRIVATE_CANARY', 'PRIVATE_NOTE_CANARY', 'DERIVED_CANARY', 'REPORT_CANARY']) assert.ok(!JSON.stringify(context).includes(secret));
const state = replayEvents(history);
assert.equal(state.tasks.get('T-secret').deleted, true);
assert.equal(state.tasks.get('T-secret').private, true);
assert.equal(state.standups['2026-11-07'].evening.text, 'REPORT_CANARY');
assert.equal(state.standups['2026-11-07'].evening.style, 'markdown');
assert.equal(state.summaries['2026-11-07'].evening.headline, 'DERIVED_CANARY');
assert.throws(() => validateProposal(history, event('v', 'task.note', { taskId: 'T-secret', text: 'bad' })), /proposal/);
assert.deepEqual(validateCommand([privateTask], privateNote), privateNote);
const opaque = event('u', 'future.operation', { preserve: { this: true } });
assert.equal(replayEvents([create, opaque]).complete, false);
assert.deepEqual(eligibleContext([create, opaque], true), []);
assert.throws(() => validateCommand([create, opaque], done), /command/);
for (const malformed of [{ ...create, status: 'invented' }, { ...create, private: 'false' }, { ...create, tags: 'tag' }, { ...create, ts: 'yesterday' }]) assert.throws(() => encodeEvent(malformed));
console.log('Real Bend bridge passed: collisions, canonical replay, completion/reopen, note identities, tombstones, reports, privacy, notes-off, incomplete-state refusal, malformed boundaries');
